#include "chassis_velocity.hpp"
#include <cassert>
#include <array>
#include <limits>
#include <iostream>
static std::array<unsigned char,32> packet(double stamp,float vx,float wz,unsigned seq){
    std::array<unsigned char,32>b{};unsigned marker=OdomWire::kMagic,pid=42;
    std::memcpy(b.data(),&stamp,8);std::memcpy(b.data()+8,&vx,4);std::memcpy(b.data()+12,&wz,4);
    std::memcpy(b.data()+16,&seq,4);std::memcpy(b.data()+24,&marker,4);std::memcpy(b.data()+28,&pid,4);
    auto c=OdomWire::checksum(b.data());std::memcpy(b.data()+20,&c,4);return b;
}
int main(){
    auto b=packet(100,.25,-.3,8);auto s=OdomWire::decode(b.data(),32,100.1);
    // Golden packet generated by Python struct.pack('=dffIIII') + FNV-1a.
    const std::string golden="00000000000059400000803e9a9999be08000000306ec8e14f444d382a000000";
    for(int i=0;i<32;++i)assert(b[i]==std::stoul(golden.substr(i*2,2),nullptr,16));
    assert(s.valid&&s.seq==8&&std::abs(s.vx_mps-.25)<1e-6);
    assert(OdomWire::decode(b.data(),32,100.6).status=="stale");
    assert(OdomWire::decode(b.data(),32,99.9).status=="future_timestamp");
    b[8]^=1;assert(!OdomWire::decode(b.data(),32,100).valid);
    b=packet(100,std::numeric_limits<float>::quiet_NaN(),0,1);assert(!OdomWire::decode(b.data(),32,100).valid);
    b=packet(0,0,0,1);assert(!OdomWire::decode(b.data(),32,100).valid);
    assert(!OdomWire::decode(b.data(),24,100).valid);
    std::cout<<"PASS odom codec: roundtrip, stale, future, checksum, invalid, legacy\n";
}
